interface MetricRecord {
  status: JobStatus
  inferenceS: number | null
  createdMs: number
  completedMs: number | null
}

/**
 * Every job the mock knows, static ledger and live jobs alike — the same source
 * `/v1/jobs` answers from, so the dashboard can never contradict the ledger.
 */
function metricRecords(): MetricRecord[] {
  const fromStatic = staticSummaries().map((s): MetricRecord => ({
    status: s.status,
    inferenceS: s.inference_seconds,
    createdMs: new Date(s.created_at).getTime(),
    completedMs: s.completed_at ? new Date(s.completed_at).getTime() : null,
  }))
  const fromLive = [...jobs.values()].map((job): MetricRecord => {
    const view = viewOf(job)
    return {
      status: view.status,
      inferenceS: view.result?.inference_seconds ?? null,
      createdMs: new Date(view.created_at).getTime(),
      completedMs: view.completed_at ? new Date(view.completed_at).getTime() : null,
    }
  })
  return [...fromLive, ...fromStatic]
}

/** Nearest rank, the gateway's percentile definition. */
function percentile(sorted: number[], p: number): number | null {
  if (sorted.length === 0) return null
  return sorted[Math.min(sorted.length - 1, Math.ceil(p * sorted.length) - 1)]
}

function percentiles(values: number[]) {
  const sorted = [...values].sort((a, b) => a - b)
  return {
    p50_s: percentile(sorted, 0.5),
    p95_s: percentile(sorted, 0.95),
    max_s: sorted.length ? sorted[sorted.length - 1] : null,
  }
}

/**
 * The trailing hour the 24h window ends on. Live by default; 'MOCK_HOUR' pins it
 * so bar positions in the visual baselines do not drift with the wall clock.
 */
function windowEndHourMs(nowMs: number): number {
  const hourMs = 3_600_000
  const live = Math.floor(nowMs / hourMs) * hourMs
  const pinned = localStorage.getItem('MOCK_HOUR')
  if (pinned === null) return live
  return Math.floor(live / 86_400_000) * 86_400_000 + Number(pinned) * hourMs
}

/**
 * 24 dense buckets ending at the current UTC hour. The static ledger's days are
 * frozen so the visual baselines stay stable, so its completions are placed by
 * hour-of-day: every bar still counts real ledger jobs, and the sum equals the
 * completed jobs the ledger lists.
 */
function throughput(records: MetricRecord[], nowMs: number) {
  const hourMs = 3_600_000
  const currentHourMs = windowEndHourMs(nowMs)
  const startHourMs = currentHourMs - 23 * hourMs
  const startHourOfDay = new Date(startHourMs).getUTCHours()
  const counts = new Array<number>(24).fill(0)
  for (const record of records) {
    if (record.status !== 'COMPLETED' || record.completedMs === null) continue
    const hourOfDay = new Date(record.completedMs).getUTCHours()
    counts[(hourOfDay - startHourOfDay + 24) % 24] += 1
  }
  return counts.map((completed, i) => ({
    hour: new Date(startHourMs + i * hourMs).toISOString(),
    completed,
  }))
}

