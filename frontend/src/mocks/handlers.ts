/**
 * The cached queue reading the mock reports, and the gateway's verdict on it.
 * `stale` follows the same rule the gateway applies — age past the threshold, or
 * no reading at all — except in 'old-trusted', which reports an old reading the
 * gateway still vouches for, so the dashboard is proven to obey the flag rather
 * than a cutoff of its own.
 */
function queueReading(mode: string | null, counts: {
  inQueue: number
  inProgress: number
  workersRunning: number
}) {
  if (mode === 'unknown') {
    return {
      status: 'unknown',
      in_queue: null,
      in_progress: null,
      workers_running: null,
      workers_idle: null,
      age_s: null,
      stale: true,
      stale_after_s: QUEUE_STALE_AFTER_S,
    }
  }
  const ageS = mode === 'stale' || mode === 'old-trusted' ? 47.3 : 4.2
  return {
    status: 'ok',
    in_queue: counts.inQueue,
    in_progress: counts.inProgress,
    workers_running: counts.workersRunning,
    workers_idle: 1 - counts.workersRunning,
    age_s: ageS,
    stale: mode === 'old-trusted' ? false : ageS > QUEUE_STALE_AFTER_S,
    stale_after_s: QUEUE_STALE_AFTER_S,
  }
}

function reconcilerReading(mode: string | null) {
  if (mode === 'unknown') {
    return {
      status: 'unknown',
      last_tick_s: null,
      stale: true,
      stale_after_s: RECONCILER_STALE_AFTER_S,
    }
  }
  const lastTickS = mode === 'stale' ? 96.4 : 1.9
  const stalled = lastTickS > RECONCILER_STALE_AFTER_S
  return {
    status: stalled ? 'stalled' : 'ok',
    last_tick_s: lastTickS,
    stale: stalled,
    stale_after_s: RECONCILER_STALE_AFTER_S,
  }
}

/**
 * MOCK_METRICS modes: 'empty' (a fresh key), 'stale' (queue and reconciler
 * readings past their thresholds), 'unknown' (no queue reading at all),
 * 'old-trusted' (an old reading the gateway still vouches for), 'single' (a
 * one-job window). Unset: the live store.
 */
function metricsSnapshot() {
  const nowMs = Date.now()
  const mode = localStorage.getItem('MOCK_METRICS')
  if (mode === 'empty') return emptyMetrics(nowMs)

  const records = metricRecords()
  const byStatus = Object.fromEntries(
    ALL_STATUSES.map((status) => [
      status,
      records.filter((r) => r.status === status).length,
    ]),
  )
  // 'single' is a gateway configured with GATEWAY_METRICS_WINDOW=1: one job in
  // the window, so its span collapses and no rate can be drawn from it
  const windowSize = mode === 'single' ? 1 : METRICS_WINDOW
  const window = records
    .filter((r) => r.status === 'COMPLETED' && r.completedMs !== null)
    .sort((a, b) => b.completedMs! - a.completedMs!)
    .slice(0, windowSize)
  const completedMs = window.map((r) => r.completedMs!)
  const inference = window
    .map((r) => r.inferenceS)
    .filter((v): v is number => v !== null)
  const wall = window.map((r) => (r.completedMs! - r.createdMs) / 1000)
  const execS = inference.reduce((sum, v) => sum + v, 0)
  const cost = (execS * GPU_RATE_USD_HR) / 3600
  const inQueue = records.filter((r) => r.status === 'QUEUED').length
  const inProgress = records.filter((r) => r.status === 'IN_PROGRESS').length
  // a fleet of one: the worker is running whenever it holds work
  const workersRunning = inProgress > 0 ? 1 : 0

  return {
    jobs: {
      by_status: byStatus,
      last_hour: records.filter((r) => nowMs - r.createdMs < 3_600_000).length,
      active_now: inQueue + inProgress,
    },
    latency: { inference: percentiles(inference), wall: percentiles(wall) },
    throughput: throughput(records, nowMs),
    cost: {
      estimated_cost_usd: cost,
      estimated_cost_usd_per_job: window.length ? cost / window.length : null,
      exec_seconds_in_window: execS,
      gpu_rate_usd_hr: GPU_RATE_USD_HR,
    },
    upstream: {
      queue: queueReading(mode, { inQueue, inProgress, workersRunning }),
      reconciler: reconcilerReading(mode),
    },
    window: windowSize,
    completed_in_window: window.length,
    window_started_at: completedMs.length
      ? new Date(Math.min(...completedMs)).toISOString()
      : null,
    window_ended_at: completedMs.length
      ? new Date(Math.max(...completedMs)).toISOString()
      : null,
    generated_at: new Date(nowMs).toISOString(),
  }
}

function unauthorized(request: Request) {
  const auth = request.headers.get('Authorization')
  if (!auth?.startsWith('Bearer ') || auth.length <= 'Bearer '.length) {
    return errorJson(
      401,
      'UNAUTHENTICATED',
      'Missing or invalid API key.',
      'Send Authorization: Bearer <secret>.',
    )
  }
  return null
}

export const handlers = [
  http.get('/health', () =>
    HttpResponse.json({ status: 'ok' }, { headers: withHeaders() }),
  ),

  http.post('/v1/jobs', async ({ request }) => {
    const denied = unauthorized(request)
    if (denied) return denied
    const idemKey = request.headers.get('Idempotency-Key')
    const replayId = idemKey ? idempotencyKeys.get(idemKey) : undefined
    const replayJob = replayId ? jobs.get(replayId) : undefined
    if (idemKey && replayJob) {
      return HttpResponse.json(viewOf(replayJob), {
        status: 200,
        headers: withHeaders(),
      })
    }
    const body = (await request.json()) as {
      prompt: string
      width?: number
      height?: number
      num_inference_steps?: number
      guidance_scale?: number
      seed?: number
      output_format?: 'png' | 'jpeg'
    }
    const now = Date.now()
    const tokens = demoTokens(body.prompt)
    if (tokens.includes('shed-one')) {
      if (now - shedOneLastMs > 60_000) {
        shedOneLastMs = now
        return errorJson(
          429,
          'QUEUE_SATURATED',
          'The endpoint queue shed this submission.',
          'Retry after 8s.',
          { 'Retry-After': '8' },
        )
      }
    } else if (tokens.includes('shed')) {
      // sheds once per idempotency key: the first retry succeeds
      if (!idemKey || !shedKeys.has(idemKey)) {
        if (idemKey) shedKeys.add(idemKey)
        return errorJson(
          429,
          'QUEUE_SATURATED',
          'The endpoint queue is saturated.',
          'Retry after 22s.',
          { 'Retry-After': '22' },
        )
      }
    }
    const scenario: Scenario =
      tokens.includes('mixed') ? 'mixed'
      : tokens.includes('blocked') ? 'blocked'
      : tokens.includes('oom') ? 'oom'
      : tokens.includes('cold') ? 'cold'
      : tokens.includes('hold') ? 'hold'
      : 'ok'
    const burst = nextBurstIndex(now)
    const seed = body.seed ?? null
    if (burst === 0) burstFirstSeed = seed
    const sameSeedBurst = burst > 0 && seed !== null && seed === burstFirstSeed
    const job: MockJob = {
      id: crypto.randomUUID(),
      prompt: body.prompt,
      width: body.width ?? 1024,
      height: body.height ?? 1024,
      steps: body.num_inference_steps ?? 28,
      guidance: body.guidance_scale ?? 3.5,
      seed,
      format: body.output_format ?? 'png',
      createdAtMs: now,
      scenario,
      cancelledAtMs: null,
      corr: correlationId(),
      burst,
      sameSeedBurst,
    }
    jobs.set(job.id, job)
    if (idemKey) idempotencyKeys.set(idemKey, job.id)
    // 'demo:drop-first': the create lands but the response is lost once per
    // key — the client's key-reusing retry then hits the replay path above
    if (tokens.includes('drop-first') && idemKey && !droppedKeys.has(idemKey)) {
      droppedKeys.add(idemKey)
      return errorJson(
        502,
        'UPSTREAM_RESET',
        'The gateway accepted the job but the response was lost.',
        'Retry with the same Idempotency-Key to recover the job.',
      )
    }
    return HttpResponse.json(
      {
        job_id: job.id,
        status: 'QUEUED',
        created_at: new Date(job.createdAtMs).toISOString(),
      },
      { status: 202, headers: withHeaders() },
    )
  }),

  http.get('/v1/jobs/:jobId/image', async ({ request, params }) => {
    const denied = unauthorized(request)
    if (denied) return denied
    const id = params.jobId as string
    const job = jobs.get(id)
    const summary = job ? null : staticSummaries().find((s) => s.job_id === id)
    if (!job && !summary) {
      return errorJson(404, 'JOB_NOT_FOUND', `No job with id ${id}.`)
    }
    // seed-keyed variants (scripts/make-seed-variants.mjs): same seed = same
    // bytes, different seed (mod 6) = visibly different image
    const seed = job ? (job.seed ?? 424242) : summary!.seed ?? 424242
    const variant = seed % 6
    const file = variant === 0 ? '/mock/sample.png' : `/mock/sample-${variant}.png`
    const res = await fetch(file)
    const bytes = await res.arrayBuffer()
    return new HttpResponse(bytes, {
      headers: withHeaders({ 'Content-Type': 'image/png' }),
    })
  }),

  http.get('/v1/jobs/:jobId', async ({ request, params }) => {
    const denied = unauthorized(request)
    if (denied) return denied
    await ensurePreviewFrames()
    const id = params.jobId as string
    const job = jobs.get(id)
    if (job) return HttpResponse.json(viewOf(job), { headers: withHeaders() })
    const summary = staticSummaries().find((s) => s.job_id === id)
    if (summary)
      return HttpResponse.json(staticView(summary), { headers: withHeaders() })
    return errorJson(404, 'JOB_NOT_FOUND', `No job with id ${id}.`)
  }),

  http.get('/v1/jobs', ({ request }) => {
    const denied = unauthorized(request)
    if (denied) return denied
    const dynamic = [...jobs.values()]
      .map((job) => ({ job, view: viewOf(job) }))
      .filter(({ view }) => view.status === 'COMPLETED')
      .map(({ job, view }): JobSummary => ({
        job_id: job.id,
        status: 'COMPLETED',
        prompt: job.prompt,
        width: job.width,
        height: job.height,
        num_inference_steps: job.steps,
        guidance_scale: job.guidance,
        output_format: job.format,
        seed: view.result!.seed,
        thumbhash: SAMPLE_THUMBHASH,
        image_url: `/v1/jobs/${job.id}/image`,
        model_version: MODEL_VERSION,
        inference_seconds: inferenceSeconds(job),
        error_code: null,
        created_at: view.created_at,
        completed_at: view.completed_at,
      }))
      .sort((a, b) => (a.created_at < b.created_at ? 1 : -1))
    return HttpResponse.json(
      { jobs: [...dynamic, ...staticSummaries()] },
      { headers: withHeaders() },
    )
  }),

  http.get('/v1/metrics', ({ request }) => {
    const denied = unauthorized(request)
    if (denied) return denied
    return HttpResponse.json(metricsSnapshot(), { headers: withHeaders() })
  }),

  http.post('/v1/jobs/:jobId/cancel', ({ request, params }) => {
    const denied = unauthorized(request)
    if (denied) return denied
    const job = jobs.get(params.jobId as string)
    if (!job) {
      return errorJson(404, 'JOB_NOT_FOUND', `No job with id ${String(params.jobId)}.`)
    }
    const view = viewOf(job)
    if (view.status === 'QUEUED' || view.status === 'IN_PROGRESS') {
      job.cancelledAtMs = Date.now()
    }
    return HttpResponse.json(viewOf(job), { headers: withHeaders() })
  }),
]
