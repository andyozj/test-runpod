function randomHex(bytes: number): string {
  const buf = new Uint8Array(bytes)
  crypto.getRandomValues(buf)
  return [...buf].map((b) => b.toString(16).padStart(2, '0')).join('')
}

/** Fresh per response, like the gateway's per-request middleware. */
function correlationId(): string {
  return randomHex(16)
}

function withHeaders(extra?: Record<string, string>): Record<string, string> {
  return { 'X-Correlation-ID': correlationId(), ...extra }
}

function errorJson(
  status: number,
  code: string,
  message: string,
  suggestion?: string,
  headers?: Record<string, string>,
) {
  return HttpResponse.json(
    {
      error: {
        code,
        message,
        suggestion: suggestion ?? null,
        correlation_id: correlationId(),
      },
    },
    { status, headers: withHeaders(headers) },
  )
}

type Scenario = 'ok' | 'blocked' | 'oom' | 'cold' | 'hold' | 'mixed'

/**
 * Scenario tokens require the demo: prefix ("demo:oom") so plain prompts
 * containing words like "cold" or "blocked" behave normally. A prompt may
 * carry several ("demo:shed-one demo:mixed").
 */
function demoTokens(prompt: string): string[] {
  return [...prompt.matchAll(/demo:([a-z-]+)/g)].map((m) => m[1])
}

