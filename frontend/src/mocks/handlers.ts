const jobs = new Map<string, MockJob>()

function fast(): boolean {
  return localStorage.getItem('MOCK_FAST') === '1'
}

/**
 * 'demo:cold' has to out-queue COLD_QUEUE_MS or the completed card shows no
 * cold split — derived from the threshold so the two cannot drift. Fast mode
 * pays the full ~22.5s here; every other scenario stays sub-second.
 */
function coldQueuedMs(isFast: boolean): number {
  return isFast ? COLD_QUEUE_MS + 2500 : Math.max(45_000, COLD_QUEUE_MS + 2500)
}

function timing(scenario: Scenario) {
  // demo pacing: ~1 stride per poll so every preview frame is observed on video
  if (localStorage.getItem('MOCK_DEMO') === '1') {
    return { queuedMs: 1500, strideMs: 900 }
  }
  const isFast = fast()
  return {
    queuedMs:
      scenario === 'cold' ? coldQueuedMs(isFast) : isFast ? 600 : 2000,
    strideMs: isFast ? 300 : 200,
  }
}

/** demo:mixed settle points: burst 1 OOMs, burst 2+ times out. */
function mixedDeadlines() {
  return fast() ? { oomMs: 14_000, timeoutMs: 22_000 } : { oomMs: 30_000, timeoutMs: 45_000 }
}

function errorBody(
  job: MockJob,
  code: string,
  message: string,
  suggestion: string,
): ErrorBody {
  return { code, message, suggestion, correlation_id: job.corr }
}

function oomError(job: MockJob): ErrorBody {
  return errorBody(
    job,
    'OOM',
    `CUDA out of memory while denoising at ${job.width}×${job.height}, ${job.steps} steps.`,
    'Reduce the resolution or step count and retry.',
  )
}

function requestEcho(job: MockJob): RequestEcho {
  return {
    prompt: job.prompt,
    width: job.width,
    height: job.height,
    num_inference_steps: job.steps,
    guidance_scale: job.guidance,
    output_format: job.format,
    ...(job.seed !== null ? { seed: job.seed } : {}),
  }
}

function viewOf(job: MockJob): JobView {
  const { queuedMs } = timing(job.scenario)
  // param-dependent pacing: total mock inference time tracks the benchmarks
  const strideMs = strideMsOf(job)
  const now = Date.now()
  const t = now - job.createdAtMs - burstOffsetMs(job)
  const iso = (ms: number) => new Date(ms).toISOString()

  const base = {
    job_id: job.id,
    request: requestEcho(job),
    created_at: iso(job.createdAtMs),
    updated_at: iso(now),
  }
  const seed = job.seed ?? 424242

  if (job.cancelledAtMs !== null) {
    return {
      ...base,
      status: 'CANCELLED',
      progress: null,
      result: null,
      error: errorBody(
        job,
        'JOB_CANCELLED',
        'The job was cancelled by the caller.',
        'Submit again to rerun it.',
      ),
      completed_at: iso(job.cancelledAtMs),
    }
  }

  if (job.scenario === 'blocked') {
    if (t < 400) {
      return { ...base, status: 'QUEUED', progress: null, result: null, error: null, completed_at: null }
    }
    return {
      ...base,
      status: 'BLOCKED',
      progress: null,
      result: null,
      error: errorBody(
        job,
        'PROMPT_BLOCKED',
        'The prompt matched the content blocklist.',
        'Rephrase the prompt and resubmit.',
      ),
      completed_at: iso(job.createdAtMs + 400),
    }
  }

  // mixed batch scenario, deterministic per burst index:
  // 0 → completes normally, 1 → previews then OOMs, 2+ → queued then times out
  if (job.scenario === 'mixed' && job.burst >= 2) {
    const { timeoutMs } = mixedDeadlines()
    if (t < timeoutMs) {
      return { ...base, status: 'QUEUED', progress: null, result: null, error: null, completed_at: null }
    }
    return {
      ...base,
      status: 'TIMED_OUT',
      progress: null,
      result: null,
      error: errorBody(
        job,
        'TIMED_OUT',
        'No worker picked the job up before the queue deadline.',
        'Resubmit; a warm worker usually starts within a second.',
      ),
      completed_at: iso(job.createdAtMs + timeoutMs),
    }
  }

  if (t < queuedMs) {
    return { ...base, status: 'QUEUED', progress: null, result: null, error: null, completed_at: null }
  }

  // deterministic mid-denoise state for visual baselines: parks at 60%
  // (forever for demo:hold; until the OOM deadline for the mixed cell)
  if (job.scenario === 'hold' || (job.scenario === 'mixed' && job.burst === 1)) {
    const { oomMs } = mixedDeadlines()
    if (job.scenario === 'mixed' && t >= oomMs) {
      return {
        ...base,
        status: 'FAILED',
        progress: { step: Math.round(0.6 * job.steps), total: job.steps, percent: 60 },
        result: null,
        error: oomError(job),
        completed_at: iso(job.createdAtMs + oomMs),
      }
    }
    return {
      ...base,
      status: 'IN_PROGRESS',
      progress: {
        step: Math.round(0.6 * job.steps),
        total: job.steps,
        percent: 60,
        ...(previewAt(60) ?? {}),
      },
      result: null,
      error: null,
      completed_at: null,
    }
  }

  const stride = Math.floor((t - queuedMs) / strideMs)
  const percent = Math.min(100, stride * 10)

  if (job.scenario === 'oom' && percent >= 40) {
    return {
      ...base,
      status: 'FAILED',
      progress: { step: Math.round((40 / 100) * job.steps), total: job.steps, percent: 40 },
      result: null,
      error: oomError(job),
      completed_at: iso(job.createdAtMs + queuedMs + 4 * strideMs),
    }
  }

  // one stride at 100% before COMPLETED, so the finalize transition is observable
  if (percent >= 100 && stride >= 11) {
    return {
      ...base,
      status: 'COMPLETED',
      progress: { step: job.steps, total: job.steps, percent: 100 },
      result: {
        image_url: `/v1/jobs/${job.id}/image`,
        thumbhash: SAMPLE_THUMBHASH,
        format: job.format,
        seed,
        width: job.width,
        height: job.height,
        model_version: MODEL_VERSION,
        inference_seconds: inferenceSeconds(job),
      },
      error: null,
      completed_at: iso(job.createdAtMs + burstOffsetMs(job) + queuedMs + 11 * strideMs),
    }
  }

  return {
    ...base,
    status: 'IN_PROGRESS',
    progress: {
      step: Math.round((percent / 100) * job.steps),
      total: job.steps,
      percent,
      ...(previewAt(percent) ?? {}),
    },
    result: null,
    error: null,
    completed_at: null,
  }
}

