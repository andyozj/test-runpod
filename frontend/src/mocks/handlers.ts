/**
 * Submissions within 3s of each other form a "burst" (a client batch). The
 * index within the burst drives deterministic per-cell timing offsets so
 * batch cells visibly finish at different moments.
 */
let burstLastMs = 0
let burstNext = 0
let burstFirstSeed: number | null | undefined
function nextBurstIndex(now: number): number {
  if (now - burstLastMs > 3000) burstNext = 0
  burstLastMs = now
  return burstNext++
}

/**
 * 'demo:shed-one' 429s exactly one submission — the first in a 60s window — so
 * a batch loses one cell and that cell's retry (after Retry-After) succeeds.
 */
let shedOneLastMs = 0

function burstOffsetMs(job: MockJob): number {
  if (job.scenario !== 'ok') return 0
  // sweep bursts (same locked seed per cell) get no stagger: per-cell wall
  // differences must come from the varied parameter alone
  if (job.sameSeedBurst) return 0
  return job.burst * (fast() ? 700 : 1500)
}

/**
 * Inference-time scale vs the 28-steps/1024² baseline, per BENCHMARKS.md:
 * steps are linear, size scales with pixel count, guidance has no time cost —
 * that is the lesson a guidance sweep teaches.
 */
function inferenceScale(job: MockJob): number {
  return (job.steps / 28) * ((job.width * job.height) / (1024 * 1024))
}

/** Per-poll progress stride; also the source of truth for inference_seconds. */
function strideMsOf(job: MockJob): number {
  const { strideMs: baseStrideMs } = timing(job.scenario)
  return Math.max(20, baseStrideMs * inferenceScale(job))
}

/**
 * Reported inference time = the 11 strides the mock actually spends denoising,
 * floored to 0.1s — so inference_seconds ≤ observed wall in every mode.
 */
function inferenceSeconds(job: MockJob): number {
  return Math.floor((11 * strideMsOf(job)) / 100) / 10
}

/**
 * Denoising previews generated by scripts/make-preview-frames.mjs from
 * sample.png. Served as progress.preview_b64 on mid-run polls (≥30%).
 */
let previewFrames: string[] = []
let previewLoad: Promise<void> | null = null

function toBase64(buf: ArrayBuffer): string {
  const bytes = new Uint8Array(buf)
  let bin = ''
  for (let i = 0; i < bytes.length; i += 0x8000) {
    bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000))
  }
  return btoa(bin)
}

function ensurePreviewFrames(): Promise<void> {
  previewLoad ??= Promise.all(
    [1, 2, 3, 4].map(async (n) => {
      const res = await fetch(`/mock/preview-${n}.jpg`)
      return toBase64(await res.arrayBuffer())
    }),
  )
    .then((frames) => {
      previewFrames = frames
    })
    .catch(() => {
      // frames missing: progress polls simply carry no preview
    })
  return previewLoad
}

function previewAt(percent: number): { preview_b64: string; preview_format: 'jpeg' } | null {
  const idx =
    percent >= 100 ? null
    : percent >= 90 ? 3
    : percent >= 70 ? 2
    : percent >= 50 ? 1
    : percent >= 30 ? 0
    : null
  const b64 = idx === null ? undefined : previewFrames[idx]
  return b64 ? { preview_b64: b64, preview_format: 'jpeg' } : null
}

